"""واحد پول: نرمال‌سازی ریال → تومان و نگهبان واحد.

قاعده‌ی کلی پروژه:
    همه‌ی ارقام پولی داخل پایپ‌لاین «تومان» هستند.
    آگهی‌هایی که قیمت را به ریال می‌نویسند باید ÷۱۰ شوند.
"""
from __future__ import annotations
import re

RIAL_PER_TOMAN = 10

# نشانه‌های ریال در متن فارسی
RIAL_HINT = re.compile(r"ریال|ريال|Rial", re.I)
TOMAN_HINT = re.compile(r"تومان|تومن|تومني|تومانی", re.I)


def text_unit(text: str) -> str:
    """'rial' | 'toman' | ''  — واحدی که در متنِ همین آگهی نوشته شده."""
    t = text or ""
    if RIAL_HINT.search(t):
        return "rial"
    if TOMAN_HINT.search(t):
        return "toman"
    return ""


def to_toman(value, context: str = "") -> float:
    """اگر متن بگوید ریال، ÷۱۰ می‌کند. پیش‌فرض: مقدار قبلاً تومان است."""
    if value is None:
        return None
    v = float(value)
    return v / RIAL_PER_TOMAN if text_unit(context) == "rial" else v


def looks_rial(value: float, local_median: float,
               lo: float = 6.0, hi: float = 13.0, band=(0.35, 2.2)) -> bool:
    """تشخیص آگهی‌ای که عددش ۱۰ برابر بازار محلی است (احتمالاً ریال).

    فقط وقتی «بله» می‌گوید که مقدار ÷۱۰ داخل باند طبیعیِ همان محله بیفتد؛
    پس محله‌ی گران (مثل قشم) دست‌نخورده می‌ماند.
    """
    if not value or not local_median or local_median <= 0:
        return False
    r = value / local_median
    if not (lo <= r <= hi):
        return False
    return band[0] <= (r / RIAL_PER_TOMAN) <= band[1]


